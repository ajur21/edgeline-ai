/* ==========================================================================
   EdgeLine AI — the NFL week hub's data (2026-11-10; owner: "I want to focus on NFL next")
   Every game of the NFL week on one view: the model's projected score and winner with its probability (a forecast,
   graded straight up, so every game has a call), the quarterbacks the model assumed, the injuries it charged for, the
   weather at outdoor stadiums, and for each moneyline side the price that would make it a lean.
   Game data only (owner rule, 2026-11-04): the projection is the production model's, the same call the board makes
   (model.forEvent, which hands NFL games to scripts/nfl.js); a price is only ever the number to clear.

   Sources, all free and asked under the pipeline's honest name (BOT_UA):
   - ESPN's public scoreboard (the week, its calendar, scores) and, through the model, each club's schedule, the league
     injury report, the standings and the listed players' game logs;
   - data/nflverse.json, the cache scripts/nfl.js keeps (CC BY 4.0), refreshed at most once a week;
   - the National Weather Service's hourly forecast for outdoor U.S. stadiums (scripts/nfl-props.js STADIUMS).
   No Odds API credit and no SportsGameOdds entity: a game the board has priced is read from data/market.js and
   data/picks-log.json on disk.

   Writes data/nfl-week.js (window.NFL_WEEK_DATA, read by js/nfl.js) and data/nfl-week-log.json (pipeline state: every
   game's forecast as of the last run before kickoff, locked at kickoff, graded straight up from ESPN's final score;
   a tie is a push; a game the log never forecast is never counted).

   Run:   node scripts/nfl-week.js             the full run (both daily workflows, after the odds run; never fails the job)
          node scripts/nfl-week.js --track     the hourly run: states, scores and grades only; one request, and none
                                               when no game of the week is in play
   Flags: --fixture     scripts/fixtures/nfl-week/ instead of the network (tests; it needs --out, so a fixture run can
                        never overwrite the real data files)
          --out <dir>   read and write the data files there
          --now <iso>   pretend it is this moment
          --quiet       no table in the log
   ========================================================================== */
