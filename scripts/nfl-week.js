/* ---------- the week ---------- */
/* the season's weeks from the scoreboard's calendar (regular season and playoffs), in order */
function weeksOf(sb) {
  const out = [];
  ((((sb && sb.leagues) || [])[0] || {}).calendar || []).forEach(function (sec) {
    const type = Number(sec && sec.value); if (type !== 2 && type !== 3) return;
    (sec.entries || []).forEach(w => out.push({ type: type, week: Number(w.value), label: w.label || "Week " + w.value, start: w.startDate, end: w.endDate }));
  });
  return out.sort((a, b) => Date.parse(a.start) - Date.parse(b.start));
}
/* the week ESPN calls current (its weeks turn on Wednesday at 3 AM Eastern), else the next one when it starts soon */
function currentWeek(weeks, now) {
  const t = now.getTime();
  return weeks.find(w => Date.parse(w.start) <= t && t < Date.parse(w.end)) || weeks.find(w => Date.parse(w.start) > t && Date.parse(w.start) - t < RULES.farDays * 864e5) || null;
}
/* one week's games as the hub reads them */
function parseWeek(sb) {
  return ((sb && sb.events) || []).map(function (e) {
    const c = e.competitions && e.competitions[0]; if (!c || !Array.isArray(c.competitors)) return null;
    const side = ha => c.competitors.find(x => x.homeAway === ha), h = side("home"), a = side("away");
    if (!h || !a || !h.team || !a.team) return null;
    const type = ((c.status || e.status || {}).type) || {}, v = c.venue || {}, ad = v.address || {};
    const team = function (x) {
      const t = x.team, rec = (x.records || []).find(r => r.type === "total" || r.name === "overall") || (x.records || [])[0];
      return { id: String(t.id), abbr: t.abbreviation, name: t.displayName, short: t.shortDisplayName || t.name || t.displayName, nick: t.name || "", location: t.location || "", record: (rec && rec.summary) || null, score: x.score != null && x.score !== "" && Number.isFinite(Number(x.score)) ? Number(x.score) : null };
    };
    return { id: String(e.id), start: e.date || c.date, timeValid: c.timeValid !== false, week: e.week && e.week.number, state: type.state || "pre", status: type.name || "", completed: !!type.completed, detail: type.shortDetail || type.detail || "",
      home: team(h), away: team(a), venue: { name: v.fullName || null, city: ad.city || null, state: ad.state || null, country: ad.country || null, indoor: v.indoor === true }, neutral: !!c.neutralSite,
      tv: (c.broadcasts || []).map(b => (b.names || []).join(", ")).filter(Boolean).join(", ") || null };
  }).filter(g => g && Number.isFinite(Date.parse(g.start)) && g.home.id !== "31" && g.home.id !== "32"); /* the Pro Bowl (AFC v NFC) is not a game to call */
}
