/* a game the forecast can no longer change: under way or over on ESPN, or past its kickoff by the run's clock */
function hasStarted(g, now) { return !OFF.test(g.status || "") && (g.state === "in" || g.state === "post" || Date.parse(g.start) <= now.getTime()); }

