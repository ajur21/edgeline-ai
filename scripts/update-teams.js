#!/usr/bin/env node
/* Team identity from ESPN's public teams endpoint -> data/teams.js (window.TEAMS_DATA).
   One request per league, no key. Logos and colours are what the site draws on every pick,
   market row, parlay leg and breakdown (see js/teams.js). Run on demand (`npm run teams`) and
   once a day from the update-data workflow; it never fails the job.
   Licensing: logos are the leagues' and clubs' marks, served from ESPN's CDN; fine for a
   demo, must be licensed before the site is sold (same caveat as the props page). */
const fs = require("fs");
const path = require("path");

const LEAGUES = [
  { sportKey: "basketball_nba", sport: "NBA", path: "basketball/nba" },
  { sportKey: "americanfootball_nfl", sport: "NFL", path: "football/nfl" },
  { sportKey: "baseball_mlb", sport: "MLB", path: "baseball/mlb" },
  { sportKey: "icehockey_nhl", sport: "NHL", path: "hockey/nhl" },
  { sportKey: "soccer_epl", sport: "Soccer", path: "soccer/eng.1" },
  { sportKey: "soccer_spain_la_liga", sport: "Soccer", path: "soccer/esp.1" },
  { sportKey: "soccer_usa_mls", sport: "Soccer", path: "soccer/usa.1" }
];
const BASE = "https://site.api.espn.com/apis/site/v2/sports/";
/* College football (2026-11-08, scripts/ncaaf.js): ESPN's teams list holds every division (763 teams), so the FBS (138) and
   FCS (127) ids come from the core API's groups 80 and 81, two more requests; the odds feed's other spellings ride along
   as `aka` (js/teams.js matches them: "Appalachian State Mountaineers" is ESPN's "App State Mountaineers") */
const CFB_CORE = "https://sports.core.api.espn.com/v2/sports/football/leagues/college-football";
async function collegeTeams() {
  const all = await get(BASE + "football/college-football/teams?limit=1000");
  const now = new Date(), season = now.getUTCMonth() + 1 >= 3 ? now.getUTCFullYear() : now.getUTCFullYear() - 1, ids = new Set();
  for (const g of ["80", "81"]) { const j = await get(CFB_CORE + "/seasons/" + season + "/types/2/groups/" + g + "/teams?limit=400"); (j.items || []).forEach(i => { const m = /teams\/(\d+)/.exec(i.$ref || ""); if (m) ids.add(m[1]); }); }
  if (!ids.size) throw new Error("no FBS or FCS ids");
  const lg = all.sports[0].leagues[0]; lg.teams = (lg.teams || []).filter(t => ids.has(String((t.team || t).id)));
  return all;
}
LEAGUES.push({ sportKey: "americanfootball_ncaaf", sport: "NCAAF", path: "football/college-football", load: collegeTeams, aka: require("./ncaaf.js").AKA });

async function get(url) {
  const res = await fetch(url, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(res.status + " " + url);
  return res.json();
}
function parseTeams(json) {
  const out = [];
  for (const s of (json && json.sports) || []) for (const l of s.leagues || []) for (const t of l.teams || []) {
    const team = t.team || t; if (!team || !team.id || team.isActive === false) continue;
    const logos = team.logos || [], full = logos.find(x => (x.rel || []).indexOf("default") !== -1 && (x.rel || []).indexOf("dark") === -1) || logos[0];
    const dark = logos.find(x => (x.rel || []).indexOf("dark") !== -1 && (x.rel || []).indexOf("scoreboard") === -1);
    out.push({
      id: String(team.id), abbr: team.abbreviation || null, name: team.displayName || team.name, short: team.shortDisplayName || team.name,
      nick: team.name || null, location: team.location || null,
      logo: full ? full.href : null, logoDark: dark ? dark.href : null,
      color: team.color ? "#" + String(team.color).replace(/^#/, "") : null, alt: team.alternateColor ? "#" + String(team.alternateColor).replace(/^#/, "") : null
    });
  }
  return out;
}
async function run(opts) {
  opts = opts || {};
  const dataDir = opts.out || path.join(__dirname, "..", "data");
  const leagues = {};
  let total = 0;
  for (const l of LEAGUES) {
    try {
      const json = opts.fetch ? await opts.fetch(l) : l.load ? await l.load() : await get(BASE + l.path + "/teams?limit=60");
      const teams = parseTeams(json);
      if (l.aka) teams.forEach(t => { if (l.aka[t.id]) t.aka = l.aka[t.id]; }); /* college football: the feed's other spellings */
      if (!teams.length) throw new Error("no teams");
      leagues[l.sportKey] = { sport: l.sport, teams: teams };
      total += teams.length;
      console.log(l.sportKey + ": " + teams.length + " teams");
    } catch (e) {
      console.log("::warning::" + l.sportKey + " skipped: " + e.message);
      /* keep whatever the last file had for this league */
      const prev = readPrevious(dataDir);
      if (prev && prev.leagues && prev.leagues[l.sportKey]) leagues[l.sportKey] = prev.leagues[l.sportKey];
    }
  }
  const data = { source: "ESPN", attribution: "Team logos and player photos via ESPN.", generatedAt: new Date().toISOString(), leagues: leagues };
  fs.mkdirSync(dataDir, { recursive: true });
  fs.writeFileSync(path.join(dataDir, "teams.js"), "/* Generated by scripts/update-teams.js from ESPN public data. Do not edit. */\nwindow.TEAMS_DATA = " + JSON.stringify(data) + ";\n");
  console.log("wrote data/teams.js: " + total + " teams in " + Object.keys(leagues).length + " leagues");
  return data;
}
function readPrevious(dataDir) {
  try { const src = fs.readFileSync(path.join(dataDir, "teams.js"), "utf8"); const w = {}; new Function("window", src)(w); return w.TEAMS_DATA; } catch (e) { return null; }
}
if (require.main === module) run().catch(e => { console.error(e); process.exit(1); });
module.exports = { run, parseTeams, LEAGUES };
