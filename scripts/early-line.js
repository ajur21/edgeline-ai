/* ==========================================================================
   EdgeLine AI — early lines: NFL and college football, tracked (2026-11-15)
   The owner asked whether posting earlier would give a bigger edge. Live data (research/timing/, outside the repo)
   found that from the moment the board first prices a game the line never moves toward our number in any sport, but
   from the open it does, and the NFL and college football are priced only when about 96% of the move from the open to
   the close has happened (their lines open days before the board's 36-hour window). College football's model reads
   only past scores, so its number on Sunday, when lines open, is the number it has on Friday. Owner, 2026-11-15:
   "lets do nfl and college football then live", choosing "tracked live first": these are NOT leans. Each game's
   number is locked when DraftKings first posts a moneyline, kept with its graded record, and becomes a lean only by
   the owner's switch once two or three weekends show the line keeps moving toward it.

   Game data only (owner rule, 2026-11-04): the probability is the production model's (model.forEvent, which hands
   NFL games to scripts/nfl.js and college games to scripts/ncaaf.js; sideProb and the per-side bar exactly as the
   board computes them). DraftKings' price is the number to clear and the line the record is kept at; it never
   enters the probability.

   Sources: ESPN's public scoreboards (the games and DraftKings' moneyline on them) and its core odds record
   (DraftKings' close, after the game), through scripts/context.js under the pipeline's honest name (BOT_UA), and
   through the model the same reads the board makes. No Odds API credit, no SportsGameOdds entity.

   - The lock: a game gets its early number the first run that sees a DraftKings moneyline on both sides and a model
     probability, while kickoff is still more than RULES.minHours away (outside the board's own window). From then on
     the number is fixed; later runs only add to its `history` (our probability and DraftKings' prices, when either
     moved), so the research can see how both travel to kickoff.
   - The side: of the two moneyline sides, the one with the larger edge (our probability minus what DraftKings'
     price implies). `clears` says whether that edge is past the side's own bar: what would have been a lean.
   - Grading (both full runs and every hourly run, ESPN only): the straight-up result (a tie is a push; a game called
     off, or not final ten days after kickoff, is void), units at the locked DraftKings price, and DraftKings' close
     from ESPN's core odds: `clv` (the close's de-vigged chance minus what the locked price implied) and `move` (the
     close's de-vigged chance minus the lock's).
   Writes data/early-line.js (window.EARLY_DATA, read by picks.html) and data/early-log.json (pipeline state).

   Run:   node scripts/early-line.js           the full run (both daily workflows; never fails the job)
          node scripts/early-line.js --track   the hourly run: grading only; no request when nothing is due
   Flags: --out <dir>  read and write the data files there;  --now <iso>  pretend it is this moment
   ========================================================================== */
"use strict";
const fs = require("fs"), path = require("path");
const context = require("./context.js");

const LEAGUES = { NFL: "americanfootball_nfl", NCAAF: "americanfootball_ncaaf" };
const RULES = {
  minHours: 36,       /* an early number is locked only while kickoff is more than this away: before the board's window */
  aheadDays: 8,       /* the scoreboards read: today and this many days ahead (Eastern) */
  gradeAfterHours: 4, /* a game is looked for as final this long after kickoff */
  voidAfterDays: 10,  /* a game not final this long after kickoff is void, never guessed */
  keepDays: 21,       /* a graded game's own row is kept this long; the record's tallies for ever */
  historyMax: 40,     /* points of history kept per game */
  showDays: 10        /* graded games listed on the page */
};
const ET = "America/New_York";
const GENERATED = "/* Generated by scripts/early-line.js. Do not edit; the next run overwrites it. */\n";
const NOTE = "Pipeline state for scripts/early-line.js: each NFL and FBS game's number locked when DraftKings first posted a moneyline, more than " + RULES.minHours + " hours before kickoff, then graded straight up at that price with DraftKings' close. Tracked, not leans. Not loaded by the site.";

const r4 = n => Math.round(n * 1e4) / 1e4;
const implied = a => a > 0 ? 100 / (a + 100) : -a / (-a + 100);
const decimal = a => a > 0 ? 1 + a / 100 : 1 + 100 / -a;
const isPrice = a => typeof a === "number" && Number.isFinite(a) && (a >= 100 || a <= -100);
const ymd = t => new Intl.DateTimeFormat("en-CA", { timeZone: ET, year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date(t)).replace(/-/g, "");
const etDay = t => new Intl.DateTimeFormat("en-CA", { timeZone: ET, year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date(t));
const OFF = /POSTPONED|CANCELED|CANCELLED|FORFEIT|SUSPENDED/i;

/* ---------- the file ---------- */
function emptyLog() { return { note: NOTE, version: 1, since: null, games: {}, tallies: {} }; }
function readLog(dir) {
  try { const l = JSON.parse(fs.readFileSync(path.join(dir, "early-log.json"), "utf8")); if (l && l.games && typeof l.games === "object") { l.tallies = l.tallies || {}; return l; } } catch (e) { /* none yet */ }
  return emptyLog();
}
/* one game a line, in a fixed order, so a run that changes nothing writes the same bytes */
function serialise(log) {
  const keys = Object.keys(log.games).sort((a, b) => Date.parse(log.games[a].commence) - Date.parse(log.games[b].commence) || a.localeCompare(b));
  const tk = Object.keys(log.tallies).sort();
  const head = ["note", "version", "since"].map(k => " " + JSON.stringify(k) + ": " + JSON.stringify(log[k] == null ? null : log[k]));
  head.push(" \"tallies\": {" + (tk.length ? "\n" + tk.map(k => "  " + JSON.stringify(k) + ": " + JSON.stringify(log.tallies[k])).join(",\n") + "\n " : "") + "}");
  head.push(" \"games\": {" + (keys.length ? "\n" + keys.map(k => "  " + JSON.stringify(k) + ": " + JSON.stringify(log.games[k])).join(",\n") + "\n " : "") + "}");
  return "{\n" + head.join(",\n") + "\n}\n";
}
function put(dir, name, text) {
  const f = path.join(dir, name); let old = null; try { old = fs.readFileSync(f, "utf8"); } catch (e) { old = null; }
  if (old === text) return false; fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(f, text); return true;
}

/* ---------- a scoreboard's games ---------- */
function gamesOf(sb, league) {
  return ((sb && sb.events) || []).map(function (e) {
    const c = e.competitions && e.competitions[0]; if (!c || !Array.isArray(c.competitors)) return null;
    const h = c.competitors.find(x => x.homeAway === "home"), a = c.competitors.find(x => x.homeAway === "away");
    if (!h || !a || !h.team || !a.team) return null;
    const st = ((c.status || e.status || {}).type) || {};
    const team = x => ({ id: String(x.team.id), abbr: x.team.abbreviation || null, name: x.team.displayName, score: x.score != null && x.score !== "" && Number.isFinite(Number(x.score)) ? Number(x.score) : null });
    return { league: league, sportKey: LEAGUES[league], id: String(e.id), commence: e.date || c.date, state: st.state || "pre", status: st.name || "", completed: !!st.completed,
      home: team(h), away: team(a), neutral: !!c.neutralSite, odds: context.scoreboardOdds(c) };
  }).filter(g => g && Number.isFinite(Date.parse(g.commence)) && g.home.id !== "31" && g.home.id !== "32");
}
/* a pick-shaped side for the context helpers (dkSide, closingOdds) */
function sideShape(g, who) { return { sportKey: g.sportKey, commence: g.commence, home: g.home.name, away: g.away.name, marketKey: "h2h", outcome: { name: g[who].name, point: null }, context: { espnEventId: g.id } }; }
function dkPair(g, snap) {
  const h = context.dkSide(sideShape(g, "home"), snap), a = context.dkSide(sideShape(g, "away"), snap);
  return h && a && isPrice(h.odds) && isPrice(a.odds) && h.fair != null ? { home: h.odds, away: a.odds, fairHome: r4(h.fair) } : null;
}

/* ---------- the model: the board's own probability and bar for both moneyline sides ---------- */
/* returns { home: { prob, bar }, away: {...}, margin, total, thin, gp } or null when the model cannot build the game */
function liveProjector(dataDir, now, src) {
  const model = require("./model.js"), nfl = require("./nfl.js"), board = require("./update-data.js");
  const cache = { ppgOf: null, officialReport: false, nfl: nfl.lazy({ file: path.join(dataDir, "nflverse.json"), now: now, fetcher: null, log: () => {} }) };
  return async function (g) {
    const H = g.home.name, A = g.away.name;
    const gm = await model.forEvent(src, context, { sportKey: g.sportKey, home: H, away: A, commence: g.commence }, now, cache);
    if (!gm) return null;
    const oH = { name: H, point: null }, oA = { name: A, point: null };
    const pH = model.sideProb(gm, "h2h", oH, H, A), pA = model.sideProb(gm, "h2h", oA, H, A);
    if (pH == null || pA == null) return null;
    const bar = o => r4(board.barOf(model.noise(gm, "h2h", o, H, A)));
    return { home: { prob: r4(pH), bar: bar(oH) }, away: { prob: r4(pA), bar: bar(oA) }, margin: Math.round(gm.margin * 10) / 10, total: Math.round(gm.total * 10) / 10, thin: !!gm.thin, gp: Math.min(gm.gpHome || gm.gp || 0, gm.gpAway || gm.gp || 0), model: gm.nflverse ? "nflverse" : g.league === "NCAAF" ? "ratings" : "margin" };
  };
}

/* ---------- the lock ---------- */
function entryFor(g, dk, pj, now) {
  const edge = who => r4(pj[who].prob - implied(dk[who]));
  const who = edge("home") >= edge("away") ? "home" : "away";
  const fair = who === "home" ? dk.fairHome : r4(1 - dk.fairHome);
  return {
    league: g.league, sportKey: g.sportKey, id: g.id, commence: new Date(Date.parse(g.commence)).toISOString(), date: etDay(Date.parse(g.commence)),
    home: { id: g.home.id, abbr: g.home.abbr, name: g.home.name }, away: { id: g.away.id, abbr: g.away.abbr, name: g.away.name }, neutral: g.neutral,
    at: now.toISOString(), hoursBefore: Math.round((Date.parse(g.commence) - now.getTime()) / 36e5 * 10) / 10,
    model: { name: pj.model, home: pj.home.prob, away: pj.away.prob, margin: pj.margin, total: pj.total, thin: pj.thin, gp: pj.gp },
    dk: { home: dk.home, away: dk.away, fairHome: dk.fairHome },
    side: who, team: g[who].name, prob: pj[who].prob, odds: dk[who], fair: fair, edge: edge(who), bar: pj[who].bar, past: r4(edge(who) - pj[who].bar), clears: edge(who) - pj[who].bar >= 0,
    history: [], status: "pending", score: null, result: null, units: null, close: null, clv: null, move: null, gradedAt: null
  };
}
/* a later read of a game already locked: one history point when our probability or DraftKings' prices moved */
function track(e, dk, pj, now) {
  const last = e.history.length ? e.history[e.history.length - 1] : { home: e.model.home, dkHome: e.dk.home, dkAway: e.dk.away };
  const pt = { at: now.toISOString(), home: pj ? pj.home.prob : last.home, dkHome: dk ? dk.home : last.dkHome, dkAway: dk ? dk.away : last.dkAway };
  if (pt.home === last.home && pt.dkHome === last.dkHome && pt.dkAway === last.dkAway) return false;
  e.history.push(pt); if (e.history.length > RULES.historyMax) e.history.splice(0, e.history.length - RULES.historyMax);
  return true;
}

/* ---------- grading ---------- */
function resultOf(e, g) {
  if (OFF.test(g.status || "")) return "Void";
  if (!g.completed || g.home.score == null || g.away.score == null) return null;
  if (g.home.score === g.away.score) return "Push";
  return (g.home.score > g.away.score) === (e.side === "home") ? "Win" : "Loss";
}
async function grade(log, now, src, sbCache) {
  const t = now.getTime(), out = { graded: 0, waiting: 0, requests: 0 };
  const due = Object.values(log.games).filter(e => e.status === "pending" && Date.parse(e.commence) + RULES.gradeAfterHours * 36e5 <= t);
  for (const e of due) {
    const k = e.sportKey + "|" + ymd(Date.parse(e.commence));
    if (!(k in sbCache)) { sbCache[k] = await src.scoreboard(e.sportKey, ymd(Date.parse(e.commence))).catch(() => null); out.requests++; }
    const g = gamesOf(sbCache[k], e.league).find(x => x.id === e.id);
    let res = g ? resultOf(e, g) : null;
    if (!res && t - Date.parse(e.commence) > RULES.voidAfterDays * 864e5) res = "Void";
    if (!res) { out.waiting++; continue; }
    e.result = res; e.status = "graded"; e.gradedAt = now.toISOString();
    e.score = g && g.home.score != null ? { home: g.home.score, away: g.away.score } : null;
    e.units = res === "Win" ? r4(decimal(e.odds) - 1) : res === "Loss" ? -1 : 0;
    if (res !== "Void") {
      let c = null; try { c = await context.closingOdds(src, Object.assign(sideShape({ sportKey: e.sportKey, commence: e.commence, home: e.home, away: e.away, id: e.id }, e.side), { odds: e.odds })); } catch (err) { c = null; }
      out.requests++;
      if (c && c.fair != null) { e.close = { odds: c.odds, fair: c.fair, open: c.open || null, source: c.source }; e.clv = r4(c.fair - implied(e.odds)); e.move = r4(c.fair - e.fair); }
    }
    out.graded++;
  }
  if (out.graded) rebuildTallies(log);
  return out;
}
/* one tally per league and Eastern game day, for all games and for the ones past their bar, kept for good */
function blank() { return { n: 0, w: 0, l: 0, push: 0, units: 0, clvN: 0, clv: 0, beat: 0, moveN: 0, move: 0, toward: 0 }; }
function addTo(t, e) {
  if (e.result === "Void") return;
  t.n++; t[e.result === "Win" ? "w" : e.result === "Loss" ? "l" : "push"]++; t.units = r4(t.units + e.units);
  if (typeof e.clv === "number") { t.clvN++; t.clv = r4(t.clv + e.clv); if (e.clv > 0) t.beat++; }
  if (typeof e.move === "number") { t.moveN++; t.move = r4(t.move + e.move); if (e.move > 0) t.toward++; }
}
function rebuildTallies(log) {
  const fresh = {};
  Object.values(log.games).forEach(function (e) {
    if (e.status !== "graded") return;
    const d = fresh[e.league + "|" + e.date] || (fresh[e.league + "|" + e.date] = { league: e.league, date: e.date, all: blank(), clears: blank() });
    addTo(d.all, e); if (e.clears) addTo(d.clears, e);
  });
  Object.keys(fresh).forEach(k => { log.tallies[k] = fresh[k]; });
}
function sum(list) {
  const t = blank();
  list.forEach(x => Object.keys(t).forEach(k => { t[k] = r4(t[k] + (x[k] || 0)); }));
  return t;
}

/* ---------- the page's file ---------- */
function publicGame(e) {
  return { league: e.league, id: e.id, commence: e.commence, date: e.date, home: e.home, away: e.away, at: e.at, hoursBefore: e.hoursBefore,
    side: e.side, team: e.team, prob: e.prob, odds: e.odds, fair: e.fair, edge: e.edge, bar: e.bar, past: e.past, clears: e.clears,
    now: e.history.length ? (function (h) { return { at: h.at, odds: e.side === "home" ? h.dkHome : h.dkAway, prob: e.side === "home" ? h.home : r4(1 - h.home) }; })(e.history[e.history.length - 1]) : null,
    status: e.status, result: e.result, score: e.score, units: e.units, clv: e.clv, move: e.move, closeOdds: e.close ? e.close.odds : null };
}
function publicData(log, now) {
  const t = now.getTime(), days = Object.values(log.tallies);
  const rec = which => ({ all: sum(days.map(d => d[which])), NFL: sum(days.filter(d => d.league === "NFL").map(d => d[which])), NCAAF: sum(days.filter(d => d.league === "NCAAF").map(d => d[which])) });
  const games = Object.values(log.games);
  const upcoming = games.filter(e => e.status === "pending").sort((a, b) => Date.parse(a.commence) - Date.parse(b.commence) || b.prob - a.prob).map(publicGame);
  const recent = games.filter(e => e.status === "graded" && t - Date.parse(e.commence) <= RULES.showDays * 864e5).sort((a, b) => Date.parse(b.commence) - Date.parse(a.commence) || b.prob - a.prob).map(publicGame);
  return {
    sample: false, generatedAt: now.toISOString(), since: log.since,
    rule: { minHours: RULES.minHours, leagues: Object.keys(LEAGUES), price: "DraftKings, from ESPN", status: "tracked, not leans" },
    record: { all: rec("all"), clears: rec("clears") }, upcoming: upcoming, recent: recent
  };
}
function write(dir, log, now) {
  const a = put(dir, "early-log.json", serialise(log));
  const data = publicData(log, now), prev = (function () { try { return fs.readFileSync(path.join(dir, "early-line.js"), "utf8"); } catch (e) { return null; } })();
  /* generatedAt alone never rewrites the page's file */
  const body = d => "window.EARLY_DATA = " + JSON.stringify(d) + ";\n";
  const same = prev && prev.replace(/"generatedAt":"[^"]*"/, "") === (GENERATED + body(data)).replace(/"generatedAt":"[^"]*"/, "");
  const b = same ? false : put(dir, "early-line.js", GENERATED + body(data));
  return a || b;
}
function trim(log, now) {
  const cut = now.getTime() - RULES.keepDays * 864e5;
  Object.keys(log.games).forEach(k => { const e = log.games[k]; if (e.status === "graded" && Date.parse(e.commence) < cut) delete log.games[k]; });
}

/* ---------- the runs ---------- */
/* opts: { out, now, src (context.source-shaped: scoreboard, odds), project (async g -> projection | null), track } */
async function run(opts) {
  opts = opts || {};
  const now = opts.now ? new Date(opts.now) : new Date(), dir = opts.out || path.join(__dirname, "..", "data");
  const src = opts.src || context.source({ named: true }), log = readLog(dir), sbCache = {};
  const counts = { locked: 0, tracked: 0, seen: 0, noLine: 0, noModel: 0, late: 0 };
  let requests = 0;
  if (!opts.track) {
    /* the scoreboards first, cached, so the model's own scoreboard reads are free */
    const cached = Object.assign({}, src, { scoreboard: async (sport, day) => { const k = sport + "|" + day; if (!(k in sbCache)) { sbCache[k] = await src.scoreboard(sport, day).catch(() => null); requests++; } return sbCache[k]; } });
    const project = opts.project || liveProjector(dir, now, cached);
    for (const league of Object.keys(LEAGUES)) {
      for (let d = 0; d <= RULES.aheadDays; d++) {
        const day = ymd(now.getTime() + d * 864e5);
        for (const g of gamesOf(await cached.scoreboard(LEAGUES[league], day), league)) {
          if (g.state !== "pre" || OFF.test(g.status) || Date.parse(g.commence) <= now.getTime()) continue;
          counts.seen++;
          const k = league + "|" + g.id, e = log.games[k], dk = g.odds ? dkPair(g, g.odds.now) : null;
          if (!e && !dk) { counts.noLine++; continue; }
          if (!e && (Date.parse(g.commence) - now.getTime()) / 36e5 <= RULES.minHours) { counts.late++; continue; } /* first seen inside the board's window: not early */
          let pj = null; try { pj = await project(g); } catch (err) { pj = null; }
          if (!e) {
            if (!pj) { counts.noModel++; continue; }
            log.games[k] = entryFor(g, dk, pj, now); counts.locked++;
            if (!log.since) log.since = { at: now.toISOString(), date: etDay(now.getTime()) };
          } else if (e.status === "pending" && track(e, dk, pj, now)) counts.tracked++;
        }
      }
    }
  }
  const gr = await grade(log, now, opts.src || src, sbCache);
  trim(log, now);
  const changed = write(dir, log, now);
  return Object.assign({ changed: changed, graded: gr.graded, waiting: gr.waiting, requests: requests + gr.requests, pending: Object.values(log.games).filter(e => e.status === "pending").length, record: publicData(log, now).record }, counts);
}
function line(r) {
  const c = r.record.clears.all, a = r.record.all.all, pts = (x, n) => n ? (x / n * 100 >= 0 ? "+" : "") + (x / n * 100).toFixed(2) + " pts" : "none";
  return (r.locked != null ? "locked " + r.locked + ", history on " + r.tracked + ", " + r.seen + " games seen (" + r.noLine + " without a line yet, " + r.late + " first seen inside " + RULES.minHours + " h, " + r.noModel + " without a model); " : "") +
    "graded " + r.graded + (r.waiting ? ", " + r.waiting + " waiting for a final" : "") + "; pending " + r.pending + "; past their bar " + c.w + "-" + c.l + (c.push ? "-" + c.push : "") + " " + (c.units >= 0 ? "+" : "") + c.units.toFixed(2) + "u, line move " + pts(c.move, c.moveN) +
    "; every game " + a.w + "-" + a.l + (a.push ? "-" + a.push : "") + ", line move " + pts(a.move, a.moveN) + ", CLV " + pts(a.clv, a.clvN) + "; ESPN requests " + r.requests + (r.changed ? "" : "; files unchanged");
}
if (require.main === module) {
  const argv = process.argv.slice(2), o = { track: argv.indexOf("--track") !== -1 };
  const i = argv.indexOf("--out"); if (i !== -1) o.out = argv[i + 1];
  const j = argv.indexOf("--now"); if (j !== -1) o.now = argv[j + 1];
  run(o).then(r => console.log("Early lines" + (o.track ? " (hourly)" : "") + ": " + line(r))).catch(e => { console.error("Early lines failed: " + e.message); process.exit(1); });
}
module.exports = { run, line, gamesOf, dkPair, entryFor, track, grade, resultOf, rebuildTallies, publicData, serialise, readLog, emptyLog, RULES, LEAGUES };
